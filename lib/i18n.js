export const dictFor = (lang) => (lang === 'es' ? es : en);

export async function getT() {
  const lang = (await cookies()).get('lang')?.value === 'es' ? 'es' : 'en';
  return { lang, t: lang === 'es' ? es : en };
}

export const fill = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => vars[k]);

export function money(n, lang) {
  return new Intl.NumberFormat(lang === 'es' ? 'es-PR' : 'en-US', { style: 'currency', currency: 'USD' }).format(Number(n) || 0);
}
